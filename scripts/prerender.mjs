// Build-time prerender: renders every route to static HTML with its own <head>
// (title, description, canonical, robots, Open Graph, JSON-LD) so crawlers and
// first paint get real content instead of an empty <div id="root">.
// Runs after `vite build` + `vite build --ssr src/entry-server.tsx` (see `npm run build`).
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "fs";
import path from "path";
import { pathToFileURL } from "url";

const root = process.cwd();
const dist = path.join(root, "dist");
const entry = path.join(root, ".prerender", "entry-server.js");

const esc = (s) =>
  String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
// JSON inside <script> must not be able to close the tag.
const jsonForScript = (obj) => JSON.stringify(obj).replace(/</g, "\\u003c");

async function main() {
  const { render, prerenderPaths, preloadAll, pageFileFor, canonicalFor, site } = await import(
    pathToFileURL(entry).href
  );
  await preloadAll();

  const template = readFileSync(path.join(dist, "index.html"), "utf8");
  const seoBlock = template.match(/<!-- SEO:START[\s\S]*?<!-- SEO:END -->/)?.[0];
  if (!seoBlock) throw new Error("dist/index.html has no <!-- SEO:START --> block to replace");
  // Favicon links are generated by site:seo; keep them as they are.
  const iconLinks = seoBlock.match(/<link rel="(?:icon|apple-touch-icon)"[^>]*>/g) ?? [];

  const domain = site.domain.replace(/\/$/, "");
  const ogImagePath = site.seo.ogImage;
  const ogImage = ogImagePath && existsSync(path.join(dist, ogImagePath)) ? `${domain}${ogImagePath}` : "";
  if (ogImagePath && !ogImage) {
    console.warn(`prerender: ${ogImagePath} is missing from public/ - pages ship without og:image.`);
  }

  const headFor = (seo, pathname) => {
    const canonical = canonicalFor(pathname);
    const blocks = seo.jsonLd ? (Array.isArray(seo.jsonLd) ? seo.jsonLd : [seo.jsonLd]) : [];
    return [
      `<title>${esc(seo.title)}</title>`,
      `<meta name="description" content="${esc(seo.description)}" />`,
      seo.noindex ? `<meta name="robots" content="noindex, follow" />` : "",
      seo.noindex ? "" : `<link rel="canonical" href="${esc(canonical)}" />`,
      ...iconLinks,
      `<meta property="og:type" content="website" />`,
      `<meta property="og:site_name" content="${esc(site.business.name)}" />`,
      `<meta property="og:url" content="${esc(canonical)}" />`,
      `<meta property="og:title" content="${esc(seo.title)}" />`,
      `<meta property="og:description" content="${esc(seo.description)}" />`,
      ogImage ? `<meta property="og:image" content="${esc(ogImage)}" />` : "",
      `<meta name="twitter:card" content="${ogImage ? "summary_large_image" : "summary"}" />`,
      `<meta name="twitter:title" content="${esc(seo.title)}" />`,
      `<meta name="twitter:description" content="${esc(seo.description)}" />`,
      ogImage ? `<meta name="twitter:image" content="${esc(ogImage)}" />` : "",
      ...blocks.map((b) => `<script type="application/ld+json" data-seo-jsonld="true">${jsonForScript(b)}</script>`),
    ]
      .filter(Boolean)
      .join("\n    ");
  };

  // The largest above-the-fold image is rendered by React, so the browser's
  // preload scanner would not see it until the bundle runs. Preload it.
  const heroPreload = (html) => {
    const img = html.match(/<img\b[^>]*\bloading="eager"[^>]*>/)?.[0];
    const src = img?.match(/\bsrc="([^"]+)"/)?.[1];
    return src ? `<link rel="preload" as="image" href="${src}" fetchpriority="high" />\n  ` : "";
  };

  // Each page's own chunk (and the shared chunks it imports) would otherwise
  // only be requested after the entry script runs. Preload them in parallel.
  const manifest = JSON.parse(readFileSync(path.join(dist, ".vite", "manifest.json"), "utf8"));
  const chunkPreloads = (pathname, page) => {
    const files = new Set();
    const walk = (key) => {
      const chunk = manifest[key];
      if (!chunk || files.has(chunk.file)) return;
      files.add(chunk.file);
      (chunk.imports ?? []).forEach(walk);
    };
    walk(pageFileFor(pathname));
    return [...files]
      .filter((f) => !page.includes(`/${f}"`))
      .map((f) => `<link rel="modulepreload" crossorigin href="/${f}">\n  `)
      .join("");
  };

  // Template comments (the SEO/WIDGETS markers) are only for the site:seo script.
  const shell = template.replace(/<!--[\s\S]*?-->\s*/g, "");

  const writePage = (pathname, file) => {
    const { html, seo } = render(pathname);
    if (!seo) throw new Error(`${pathname}: page rendered no <Seo> component`);
    let page = shell.replace(/<title>[\s\S]*?<\/title>/, "");
    page = page.replace(/<meta (?:name|property)="(?:description|og:[^"]+|twitter:[^"]+)"[^>]*>\s*/g, "");
    page = page.replace(/<link rel="(?:icon|apple-touch-icon|canonical)"[^>]*>\s*/g, "");
    // The LCP image goes first in <head>, ahead of the stylesheet and scripts.
    const hero = heroPreload(html);
    if (hero) page = page.replace(/(<meta name="viewport"[^>]*>\s*)/, (m) => `${m}${hero}  `);
    const preloads = chunkPreloads(pathname, page);
    page = page.replace("</head>", () => `  ${headFor(seo, pathname)}\n  ${preloads}</head>`);
    page = page.replace('<div id="root"></div>', () => `<div id="root">${html}</div>`);
    const out = path.join(dist, file);
    mkdirSync(path.dirname(out), { recursive: true });
    writeFileSync(out, page);
  };

  const paths = prerenderPaths();
  for (const p of paths) writePage(p, p === "/" ? "index.html" : `${p.slice(1)}.html`);
  writePage("/404", "404.html");
  // The manifest only exists for this script; do not deploy it.
  rmSync(path.join(dist, ".vite"), { recursive: true, force: true });
  console.log(`prerender: ${paths.length} routes + 404.html`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
